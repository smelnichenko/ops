#!/usr/bin/env python3
"""Merge pending/*.md into INVESTIGATE-LIST.md and investigate-list.tsv - sources for future investigation.

    python3 -I investigate_list.py

These sources are excluded today only because something is still open. A malformed file is
reported and the run exits 1 without writing.
"""
import csv
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "pending"
COLUMNS = ["Hosts", "Source", "What it would give", "Why it is not included", "What would settle it", "Obstacle"]
KINDS = ("terms-unclear", "needs-approval", "refused", "unverified")
HOST = re.compile(r"^(\*\.)?[a-z\d]([a-z\d-]*[a-z\d])?(\.[a-z\d]([a-z\d-]*[a-z\d])?)+$")


def excluded_hosts():
    path = HERE / "exclude-list.tsv"
    if not path.exists():
        return {}
    with path.open(encoding="utf-8") as fh:
        return {r["host"]: r["kind"] for r in csv.DictReader(fh, delimiter="\t")}


def read(path, banned):
    lines = path.read_text(encoding="utf-8").splitlines()
    title = lines[0].lstrip("# ").strip() if lines else path.stem
    date = next((l.split(":", 1)[1].strip() for l in lines if l.startswith("Date:")), "")
    rows, problems = [], []
    table = [l for l in lines if l.startswith("|")]
    if not table:
        if not any(l.strip() == "None." for l in lines):
            problems.append(f"{path.name}: neither a table nor 'None.'")
        return title, date, rows, problems
    header = [c.strip() for c in table[0].strip().strip("|").split("|")]
    if header != COLUMNS:
        return title, date, rows, [f"{path.name}: table header is {header}, wanted {COLUMNS}"]
    for line in table[2:]:
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != len(COLUMNS):
            problems.append(f"{path.name}: a row has {len(cells)} cells: {line[:80]}")
            continue
        hosts = [h.strip().strip("`") for h in cells[0].split(",") if h.strip()]
        bad = [h for h in hosts if not HOST.match(h)]
        if bad or not hosts:
            problems.append(f"{path.name}: not host names: {bad or cells[0]}")
        elif cells[5] not in KINDS:
            problems.append(f"{path.name}: Obstacle is '{cells[5]}', wanted one of {KINDS}")
        else:
            rows.append((hosts, cells))
    return title, date, rows, problems


def main():
    banned = excluded_hosts()
    files = sorted(SRC.glob("*.md"))
    problems, md, tsv, by_kind = [], [], [], dict.fromkeys(KINDS, 0)
    for path in files:
        title, date, rows, bad = read(path, banned)
        problems += bad
        md += [f"## {title.split(' - ')[0]}", ""]
        if not rows:
            md += ["None.", ""]
            continue
        md += [f"As of {date or 'date missing'}.", "",
               "| " + " | ".join(COLUMNS) + " |", "|" + "---|" * len(COLUMNS)]
        for hosts, cells in rows:
            md.append("| " + " | ".join([", ".join(hosts)] + cells[1:]) + " |")
            by_kind[cells[5]] += 1
            for host in hosts:
                tsv.append("\t".join([host, path.stem, cells[5], cells[1], cells[3], cells[4]]))
        md.append("")
    if problems:
        print("NOT WRITTEN:")
        for p in problems:
            print(" -", p)
        return 1
    total = sum(by_kind.values())
    head = ["# Sources for future investigation", "",
            "Generated by `investigate_list.py` from `pending/`; do not edit. These sources are excluded today - they "
            "are not on the include list - only because something is still open: unclear terms, access that someone "
            "must grant, a host that refused the request, or a finding the check could not confirm. Each row says "
            "what would settle it. Explicitly prohibited sources are in `EXCLUDE-LIST.md`, not here. "
            "Rules: `briefs/INVESTIGATE-BRIEF.md`.", "",
            f"{total} sources from {len(files)} country files: " + ", ".join(f"{by_kind[k]} {k}" for k in KINDS) + ". "
            "Machine-readable: `investigate-list.tsv` (host, unit, obstacle, source, why not included, what would settle it).", ""]
    (HERE / "INVESTIGATE-LIST.md").write_text("\n".join(head + md).rstrip("\n") + "\n", encoding="utf-8")
    (HERE / "investigate-list.tsv").write_text(
        "host\tunit\tobstacle\tsource\twhy_not_included\twhat_would_settle_it\n" + "\n".join(sorted(tsv)) + ("\n" if tsv else ""),
        encoding="utf-8")
    print(f"investigate list: {total} sources, {len({l.split(chr(9))[0] for l in tsv})} hosts, {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
