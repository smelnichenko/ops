#!/usr/bin/env python3
"""Merge included/*.md into INCLUDE-LIST.md and include-list.tsv - the list a program acts on.

    python3 -I include_list.py

Rule: a source that is not on the include list is excluded. A malformed file, or a host that is
also on the exclude list, is reported and the run exits 1 without writing.
"""
import csv
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "included"
COLUMNS = ["Hosts", "Source", "What it gives", "How to read it", "Key", "Why it is allowed", "Kind"]
KINDS = ("vacancies", "archive", "employer-feed", "company-register")
KEYS = ("none", "free self-service")
HOST = re.compile(r"^(\*\.)?[a-z\d]([a-z\d-]*[a-z\d])?(\.[a-z\d]([a-z\d-]*[a-z\d])?)+$")


def excluded_hosts():
    path = HERE / "exclude-list.tsv"
    if not path.exists():
        return {}
    with path.open(encoding="utf-8") as fh:
        return {r["host"]: r["kind"] for r in csv.DictReader(fh, delimiter="\t")}


def read(path, banned):
    lines = path.read_text(encoding="utf-8").splitlines()
    title = lines[0].lstrip("# ").strip() if lines else path.stem
    date = next((l.split(":", 1)[1].strip() for l in lines if l.startswith("Date:")), "")
    rows, problems = [], []
    table = [l for l in lines if l.startswith("|")]
    if not table:
        if not any(l.strip() == "None." for l in lines):
            problems.append(f"{path.name}: neither a table nor 'None.'")
        return title, date, rows, problems
    header = [c.strip() for c in table[0].strip().strip("|").split("|")]
    if header != COLUMNS:
        return title, date, rows, [f"{path.name}: table header is {header}, wanted {COLUMNS}"]
    for line in table[2:]:
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != len(COLUMNS):
            problems.append(f"{path.name}: a row has {len(cells)} cells: {line[:80]}")
            continue
        hosts = [h.strip().strip("`") for h in cells[0].split(",") if h.strip()]
        bad = [h for h in hosts if not HOST.match(h)]
        if bad or not hosts:
            problems.append(f"{path.name}: not host names: {bad or cells[0]}")
        elif cells[4] not in KEYS:
            problems.append(f"{path.name}: Key is '{cells[4]}', wanted one of {KEYS}")
        elif cells[6] not in KINDS:
            problems.append(f"{path.name}: Kind is '{cells[6]}', wanted one of {KINDS}")
        else:
            # a whole-site prohibition and an inclusion cannot both stand; a partial robots rule can
            clash = [h for h in hosts if banned.get(h.replace("*.", "")) in ("terms", "robots.txt")]
            if clash:
                problems.append(f"{path.name}: {clash} is on the exclude list - resolve before including")
            else:
                rows.append((hosts, cells))
    return title, date, rows, problems


def main():
    banned = excluded_hosts()
    files = sorted(SRC.glob("*.md"))
    problems, md, tsv, by_kind = [], [], [], dict.fromkeys(KINDS, 0)
    for path in files:
        title, date, rows, bad = read(path, banned)
        problems += bad
        md += [f"## {title.split(' - ')[0]}", ""]
        if not rows:
            md += ["None.", ""]
            continue
        md += [f"Seen by the independent check on {date or 'date missing'}.", "",
               "| " + " | ".join(COLUMNS) + " |", "|" + "---|" * len(COLUMNS)]
        for hosts, cells in rows:
            md.append("| " + " | ".join([", ".join(hosts)] + cells[1:]) + " |")
            by_kind[cells[6]] += 1
            for host in hosts:
                tsv.append("\t".join([host, path.stem, cells[6], cells[4], cells[1], cells[3], cells[5]]))
        md.append("")
    if problems:
        print("NOT WRITTEN:")
        for p in problems:
            print(" -", p)
        return 1
    total = sum(by_kind.values())
    head = ["# Included sources - the list a program acts on", "",
            "**A source that is not on this list is excluded.** Generated by `include_list.py` from `included/`; "
            "do not edit. A source is here only when the independent check confirmed it, its terms allow reading "
            "for one's own job search (an open licence or the publisher's own statement), a program can read it "
            "without anyone's approval, and it is not on the exclude list. Rules: `briefs/INCLUDED-BRIEF.md`.", "",
            f"{total} sources from {len(files)} country files: " + ", ".join(f"{by_kind[k]} {k}" for k in KINDS) + ". "
            "Machine-readable: `include-list.tsv` (host, unit, kind, key, source, how to read it, why it is allowed).", ""]
    (HERE / "INCLUDE-LIST.md").write_text("\n".join(head + md).rstrip("\n") + "\n", encoding="utf-8")
    (HERE / "include-list.tsv").write_text(
        "host\tunit\tkind\tkey\tsource\thow_to_read\twhy_allowed\n" + "\n".join(sorted(tsv)) + ("\n" if tsv else ""),
        encoding="utf-8")
    print(f"include list: {total} sources, {len({l.split(chr(9))[0] for l in tsv})} hosts, {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
