#!/usr/bin/env python3
"""Merge prohibited/*.md into EXCLUDE-LIST.md (for reading) and exclude-list.tsv (for programs).

    python3 -I exclude_list.py

One row per source in the .md; one row per host in the .tsv. A malformed file is reported and the
run exits 1 without writing, so a broken list never replaces a good one.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "prohibited"
COLUMNS = ["Hosts", "Source", "What is forbidden", "Clause (quoted)", "Clause read at", "Kind"]
HOST = re.compile(r"^[a-z\d]([a-z\d-]*[a-z\d])?(\.[a-z\d]([a-z\d-]*[a-z\d])?)+$")


def read(path):
    """(title, status, date, rows, problems) for one prohibited/<unit>.md."""
    lines = path.read_text(encoding="utf-8").splitlines()
    title = lines[0].lstrip("# ").strip() if lines else path.stem
    status = next((l.split(":", 1)[1].strip() for l in lines if l.startswith("Status:")), "")
    date = next((l.split(":", 1)[1].strip() for l in lines if l.startswith("Date:")), "")
    rows, problems = [], []
    if not status.startswith(("checked", "first pass")):
        problems.append(f"{path.name}: Status line missing or not 'checked' / 'first pass'")
    table = [l for l in lines if l.startswith("|")]
    if not table:
        if not any(l.strip() == "None found." for l in lines):
            problems.append(f"{path.name}: neither a table nor 'None found.'")
        return title, status, date, rows, problems
    header = [c.strip() for c in table[0].strip().strip("|").split("|")]
    if header != COLUMNS:
        problems.append(f"{path.name}: table header is {header}, wanted {COLUMNS}")
        return title, status, date, rows, problems
    for line in table[2:]:
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != len(COLUMNS):
            problems.append(f"{path.name}: a row has {len(cells)} cells: {line[:80]}")
            continue
        hosts = [h.strip().strip("`") for h in cells[0].split(",") if h.strip()]
        bad = [h for h in hosts if not HOST.match(h)]
        if bad or not hosts:
            problems.append(f"{path.name}: not host names: {bad or cells[0]}")
            continue
        if cells[5] not in ("terms", "robots.txt"):
            problems.append(f"{path.name}: Kind is '{cells[5]}', wanted terms or robots.txt")
            continue
        rows.append((hosts, cells))
    return title, status, date, rows, problems


def main():
    files = sorted(SRC.glob("*.md"))
    problems, md, tsv, sources, checked = [], [], [], 0, 0
    for path in files:
        title, status, date, rows, bad = read(path)
        problems += bad
        unit = path.stem
        md += [f"## {title.split(' - ')[0]}", "", f"{status or 'status missing'}; clauses read {date or 'date missing'}.", ""]
        if not rows:
            md += ["None found.", ""]
            continue
        md += ["| " + " | ".join(COLUMNS) + " |", "|" + "---|" * len(COLUMNS)]
        for hosts, cells in rows:
            md.append("| " + " | ".join([", ".join(hosts)] + cells[1:]) + " |")
            sources += 1
            checked += status.startswith("checked")
            for host in hosts:
                tsv.append("\t".join([host, unit, "checked" if status.startswith("checked") else "first-pass",
                                      cells[5], cells[1], cells[2], cells[4]]))
        md.append("")
    if problems:
        print("NOT WRITTEN:")
        for p in problems:
            print(" -", p)
        return 1
    hosts_total = len({line.split("\t")[0] for line in tsv})
    head = ["# Explicitly prohibited sources - exclude list", "",
            "Generated by `exclude_list.py` from `prohibited/`; do not edit. What goes in and what stays out is in "
            "`briefs/PROHIBITED-BRIEF.md`: only sources whose own terms or robots.txt explicitly forbid automated "
            "reading or copying, with the clause quoted from the publisher's page. A technical refusal, an unclear "
            "term, or a paid service is NOT in this list.", "",
            f"{sources} sources ({checked} confirmed by the independent check, {sources - checked} first pass), "
            f"{hosts_total} host names, from {len(files)} country files. "
            "Machine-readable: `exclude-list.tsv` (host, unit, status, kind, source, what is forbidden, clause URL).", ""]
    (HERE / "EXCLUDE-LIST.md").write_text("\n".join(head + md).rstrip("\n") + "\n", encoding="utf-8")
    (HERE / "exclude-list.tsv").write_text(
        "host\tunit\tstatus\tkind\tsource\twhat_is_forbidden\tclause_url\n" + "\n".join(sorted(tsv)) + ("\n" if tsv else ""),
        encoding="utf-8")
    print(f"exclude list: {sources} sources, {hosts_total} hosts, {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
