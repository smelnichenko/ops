#!/usr/bin/env python3
"""Write STATUS.md: per country, which of research / check / report exists, and the check's verdicts.

    python3 -I status.py
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ZONES = {
    "EU-wide": [("00", "EU-wide")],
    "Nordics and Baltics": [("DK", "Denmark"), ("EE", "Estonia"), ("FI", "Finland"), ("LT", "Lithuania"),
                            ("LV", "Latvia"), ("SE", "Sweden")],
    "Western Europe": [("BE", "Belgium"), ("FR", "France"), ("IE", "Ireland"), ("LU", "Luxembourg"),
                       ("NL", "Netherlands")],
    "Germany and Austria": [("AT", "Austria"), ("DE", "Germany")],
    "Central Europe": [("CZ", "Czechia"), ("HU", "Hungary"), ("PL", "Poland"), ("SI", "Slovenia"),
                       ("SK", "Slovakia")],
    "Southwest Europe": [("ES", "Spain"), ("IT", "Italy"), ("MT", "Malta"), ("PT", "Portugal")],
    "Southeast Europe": [("BG", "Bulgaria"), ("CY", "Cyprus"), ("GR", "Greece"), ("HR", "Croatia"),
                         ("RO", "Romania")],
}
VERDICTS = ["CONFIRMED", "CORRECTED", "WRONG", "UNVERIFIED", "NOT DISPROVED"]
VERDICT_CELL = re.compile(r"^\**\s*(NOT DISPROVED|CONFIRMED|CORRECTED|WRONG|UNVERIFIED)\b")


def verdicts(path):
    counts = dict.fromkeys(VERDICTS, 0)
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("|"):
            continue
        for cell in line.strip().strip("|").split("|"):
            hit = VERDICT_CELL.match(cell.strip())
            if hit:
                counts[hit.group(1)] += 1
                break
    return counts


def main():
    rows, totals, done = [], dict.fromkeys(VERDICTS, 0), {"research": 0, "check": 0, "report": 0}
    for zone, units in ZONES.items():
        for code, name in units:
            stem = f"{code}-{name}.md"
            have = {kind: (HERE / kind / stem).exists() for kind in done}
            for kind, present in have.items():
                done[kind] += present
            counts = verdicts(HERE / "check" / stem) if have["check"] else None
            if counts:
                for key in VERDICTS:
                    totals[key] += counts[key]
            cells = [str(counts[v]) for v in VERDICTS] if counts else ["-"] * len(VERDICTS)
            mark = {True: "yes", False: "**no**"}
            rows.append(f"| {zone} | {code} | {name} | {mark[have['research']]} | {mark[have['check']]} | "
                        + " | ".join(cells) + f" | {mark[have['report']]} |")
    units_total = sum(len(u) for u in ZONES.values())
    out = ["# Status", "",
           "Generated by `status.py`; do not edit. Verdict counts are the first verdict word of each row "
           "of the check tables.", "",
           f"Of {units_total} units (27 countries + the EU-wide layer): research {done['research']}, "
           f"check {done['check']}, report section {done['report']}.",
           "Checked claims so far: " + ", ".join(f"{totals[v]} {v.lower()}" for v in VERDICTS) + ".", "",
           "| Zone | Code | Unit | Research | Check | Confirmed | Corrected | Wrong | Unverified | Not disproved | Report |",
           "|---|---|---|---|---|---|---|---|---|---|---|", *rows]
    (HERE / "STATUS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"research {done['research']}/{units_total}, check {done['check']}/{units_total}, "
          f"report {done['report']}/{units_total}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
