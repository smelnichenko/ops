#!/usr/bin/env python3
"""Regenerate by-country/ from notes/: one file per EU country.

Each country file holds that country's section of its region's research notes and, when the
independent check has reached it, that country's section of the region's verification file.
Nothing is rewritten: sections are copied as they stand. Run it again after any change in notes/.

    python3 -I split_by_country.py
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
NOTES = HERE / "notes"
OUT = HERE / "by-country"

# region file stem -> [(ISO code, name as it starts the section heading)]
REGIONS = {
    "nordics_baltics": [("DK", "Denmark"), ("FI", "Finland"), ("SE", "Sweden"),
                        ("EE", "Estonia"), ("LV", "Latvia"), ("LT", "Lithuania")],
    "western_europe": [("FR", "France"), ("BE", "Belgium"), ("NL", "Netherlands"),
                       ("LU", "Luxembourg"), ("IE", "Ireland")],
    "germany_austria": [("DE", "Germany"), ("AT", "Austria")],
    "central_europe": [("PL", "Poland"), ("CZ", "Czechia"), ("SK", "Slovakia"),
                       ("HU", "Hungary"), ("SI", "Slovenia")],
    "southwest_europe": [("ES", "Spain"), ("PT", "Portugal"), ("IT", "Italy"), ("MT", "Malta")],
    "southeast_europe": [("GR", "Greece"), ("CY", "Cyprus"), ("HR", "Croatia"),
                         ("RO", "Romania"), ("BG", "Bulgaria")],
}
VERDICTS = ["CONFIRMED", "CORRECTED", "WRONG", "UNVERIFIED", "NOT DISPROVED", "INFERENCE"]
VERDICT_CELL = re.compile(r"^\**\s*(NOT DISPROVED|CONFIRMED|CORRECTED|WRONG|UNVERIFIED|INFERENCE)\b")


def sections(text, level):
    """Split markdown into (heading, body) at headings of exactly `level` #; text before the first is dropped."""
    mark = "#" * level + " "
    found, heading, body = [], None, []
    for line in text.splitlines():
        if line.startswith(mark):
            if heading is not None:
                found.append((heading, "\n".join(body).strip("\n")))
            heading, body = line[len(mark):].strip(), []
        elif heading is not None:
            body.append(line)
    if heading is not None:
        found.append((heading, "\n".join(body).strip("\n")))
    return found


def bare(heading):
    """Heading without a leading '4. ' style number."""
    return re.sub(r"^\d+\.\s*", "", heading)


def research_parts(stem, name):
    path = NOTES / f"{stem}.md"
    if not path.exists():
        return []
    parts = []
    for heading, body in sections(path.read_text(encoding="utf-8"), 2):
        start = bare(heading).lower()
        if start.startswith(name.lower()) or (stem == "germany_austria" and start.startswith("both countries")):
            parts.append((heading, body))
    return parts


def check_parts(stem, name):
    path = NOTES / f"verification_{stem}.md"
    if not path.exists():
        return None
    text = path.read_text(encoding="utf-8")
    if stem == "germany_austria":
        # One "## Results per unit" section with a "###" per unit: Austria is its own unit, every other unit is German.
        parts = []
        for heading, body in sections(text, 2):
            if heading.lower().startswith("results per unit"):
                for unit, unit_body in sections(body, 3):
                    is_austria = unit.lower().startswith("austria")
                    if is_austria == (name == "Austria"):
                        parts.append((unit, unit_body))
        return parts
    return [(h, b) for h, b in sections(text, 2) if bare(h).lower().startswith(name.lower())]


def count_verdicts(parts):
    counts = dict.fromkeys(VERDICTS, 0)
    for _, body in parts:
        for line in body.splitlines():
            if not line.startswith("|"):
                continue
            for cell in line.strip().strip("|").split("|"):
                hit = VERDICT_CELL.match(cell.strip())
                if hit:
                    counts[hit.group(1)] += 1
                    break
    return counts


def main():
    OUT.mkdir(exist_ok=True)
    wanted, rows = set(), []
    for stem, countries in REGIONS.items():
        for code, name in countries:
            research = research_parts(stem, name)
            check = check_parts(stem, name)
            out = [f"# {name} ({code}) - free online address data sources", "",
                   "Generated by `split_by_country.py` from the region files; do not edit here, edit `notes/` and rerun.",
                   "",
                   f"- Research notes: `notes/{stem}.md`",
                   f"- Independent check: `notes/verification_{stem}.md`"
                   + ("" if check else " - **no section for this country yet: NOT independently checked**"),
                   "- Region-wide parts (method notes, cross-country comparison, the list of corrections) stay in those two files.",
                   "- EU-wide sources that also cover this country (OpenAddresses, Overture, GISCO Address API, GeoNames, "
                   "OpenStreetMap): `notes/pan_european_sources.md` and its check.",
                   ""]
            out += ["## Research notes (first layer, as the researcher wrote them)", ""]
            if not research:
                out += ["No section found for this country in the region notes.", ""]
            for heading, body in research:
                out += [f"**Source section: {heading}**", "", body, ""]
            out += ["## Independent check (claim by claim)", ""]
            if not check:
                out += ["Not checked yet.", ""]
            else:
                for heading, body in check:
                    out += [f"**Source section: {heading}**", "", body, ""]
            target = OUT / f"{code}-{name}.md"
            target.write_text("\n".join(out).rstrip("\n") + "\n", encoding="utf-8")
            wanted.add(target.name)
            counts = count_verdicts(check or [])
            rows.append((code, name, stem, sum(b.count("\n") + 1 for _, b in research), bool(check), counts))

    rows.sort()
    index = ["# By country", "",
             "Generated by `split_by_country.py`; rerun it after any change in `notes/`.",
             "Verdict counts are counted by the script from the check tables (first verdict word in each row); "
             "the checkers' own totals in the region files count mixed rows by hand and can differ by a few.", "",
             "| Code | Country | Region file | Research lines | Checked | Confirmed | Corrected | Wrong | Unverified | Not disproved |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for code, name, stem, lines, checked, c in rows:
        cells = [str(c[v]) for v in ("CONFIRMED", "CORRECTED", "WRONG", "UNVERIFIED", "NOT DISPROVED")] if checked else ["-"] * 5
        index.append(f"| {code} | [{name}]({code}-{name}.md) | `{stem}` | {lines} | {'yes' if checked else '**no**'} | "
                     + " | ".join(cells) + " |")
    index += ["", "EU-wide layer (legal framework, INSPIRE, OpenAddresses, OpenStreetMap, Overture, GISCO, GeoNames): "
              "`../notes/pan_european_sources.md`, check in `../notes/verification_pan_european_sources.md`."]
    (OUT / "README.md").write_text("\n".join(index) + "\n", encoding="utf-8")
    wanted.add("README.md")

    for stale in OUT.glob("*.md"):
        if stale.name not in wanted:
            stale.unlink()
    missing = [f"{code} research" for code, _, _, lines, _, _ in rows if lines == 0]
    print(f"wrote {len(rows)} country files; checked: {sum(1 for r in rows if r[4])}; not checked: "
          + (", ".join(r[0] for r in rows if not r[4]) or "none"))
    if len(rows) != 27 or missing:
        print("PROBLEM:", len(rows), "countries;", "empty:", missing)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
